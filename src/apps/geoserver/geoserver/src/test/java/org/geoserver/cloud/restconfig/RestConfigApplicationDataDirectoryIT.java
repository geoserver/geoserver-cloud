package org.geoserver.cloud.restconfig;

import java.nio.file.Path;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

@ActiveProfiles("datadir")
class RestConfigApplicationDataDirectoryIT extends RestConfigApplicationTest {

    static @TempDir Path datadir;

    // gwc is on the combined app's classpath whichever services are enabled, and its default cache
    // location derives from the data-directory location, only known here as a dynamic property
    @DynamicPropertySource
    static void setUpDataDir(DynamicPropertyRegistry registry) {
        registry.add("geoserver.backend.data-directory.location", datadir::toAbsolutePath);
        registry.add("gwc.cache-directory", () -> datadir.resolve("gwc").toAbsolutePath());
    }
}
